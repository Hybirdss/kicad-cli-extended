#!/usr/bin/env python3
"""Turn a results JSON from run_bench.py into the short Markdown summary in bench/results/.

Every figure in the summary is read from the JSON, so the README's numbers stay traceable to
one file.

    python bench/summarize.py bench/results/results-2026-10-29.json
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Dict, List

TASKS = [("erc", "ERC summary"), ("drc", "DRC"), ("bom", "BOM"), ("gerber_drill", "Gerber + drill")]
SIDES = [("kce", "`kce`"), ("mixelpixx", "mixelpixx"), ("lamaalrajih", "lamaalrajih")]


def num(n: Any) -> str:
    return f"{n:,}" if isinstance(n, int) else str(n)


def context_rows(ctx: Dict[str, Any]) -> List[str]:
    rows = []
    kce = ctx["kce"]
    rows.append(f"| kce (skill) | 1 shell command | **{num(kce['always_tokens'])}** | "
                f"{num(kce['with_skill_tokens'])} | "
                f"{num(kce['on_demand']['commands_reference'])} (`COMMANDS.md`, on demand) |")
    for key, c in ctx.items():
        if key == "kce":
            continue
        label = "mixelpixx, default (all tools)" if key == "mixelpixx" else (
            f"mixelpixx, `{key.split(':')[1]}` config" if ":" in key else f"{key}, default")
        listed = (f"{c['resources']} resources, {c['resource_templates']} resource templates, "
                  f"{c['prompts']} prompts")
        rows.append(f"| {label} | {c['tools']} | **{num(c['always_tokens'])}** | "
                    f"{num(c['always_tokens'])} | {listed} |")
    return rows


def task_rows(result: Dict[str, Any]) -> List[str]:
    rows = []
    summary = result["summary"]
    for task, title in TASKS:
        by_side = summary.get(task, {})
        for side, label in SIDES:
            s = by_side.get(side, {})
            if not s.get("supported"):
                rows.append(f"| {title} | {label} | — | no tool | — | — | — |")
                continue
            total = s["request_tokens"] + s["response_tokens"]
            times = [r["seconds"] for r in result["tasks"][task][side]["runs"]]
            rows.append(f"| {title} | {label} | {s['calls']} | "
                        f"{num(s['request_tokens'])} + {num(s['response_tokens'])} | {num(total)} | "
                        f"{s['median_seconds']:.2f} | {min(times):.3f}–{max(times):.3f} |")
    return rows


def failed_runs(result: Dict[str, Any]) -> List[str]:
    bad = []
    for task, by in result["tasks"].items():
        for side, slot in by.items():
            for i, run in enumerate(slot.get("runs", [])):
                if run["ok"] and run["verify"].get("produced"):
                    continue
                head = next((d["response_head"] for d in run["detail"] if not d["ok"]), "")
                head = " ".join(head.split())[:200]
                bad.append(f"* `{task}` / `{side}` run {i + 1}: ok={run['ok']}, "
                           f"produced={bool(run['verify'].get('produced'))}, {run['seconds']} s — {head}")
    return bad


def render(result: Dict[str, Any], json_name: str) -> str:
    ctx = result["context"]
    m = result["machine"]
    runs = [(t, s, v) for t, by in result["summary"].items() for s, v in by.items() if v.get("supported")]
    ok = sum(v["ok_runs"] for _, _, v in runs)
    total_runs = sum(v["runs"] for _, _, v in runs)
    produced = sum(v["produced_runs"] for _, _, v in runs)
    ran = {s for t, by in result["summary"].items() for s, v in by.items() if v.get("ok_runs")}
    load = m.get("loadavg_at_end") or []
    gate = result.get("load_gate") or {}
    max_load = gate.get("max_load", (m.get("cpus") or 1) * 0.25)
    rep_loads = gate.get("reps", [])
    quiet = (max_load > 0 and len(rep_loads) == result["reps"]
             and all(r.get("loadavg") is not None and r["loadavg"] < max_load
                     and not r["started_above_limit"] for r in rep_loads))
    load_mark = (m.get("loadavg_at_start") or [None])[0]
    if load_mark is None:
        load_mark = load[0] if load else None
    servers = result["servers"]
    out = [
        f"# Benchmark results — {result['date'][:10]}",
        "",
        "Generated by [`../summarize.py`](../summarize.py) from "
        f"[`{json_name}`]({json_name}); every figure below is read from that file.",
        "",
        "Measured with the harness and method in [`../METHOD.md`](../METHOD.md) on the "
        f"`{result['demo_project']}` demo shipped with KiCad (copied fresh for every run).",
        "",
        "## Conditions",
        "",
        f"* Date: {result['date'][:10]} (UTC).",
        f"* KiCad {result['kicad']}, `{result['kce']}` from this repository.",
        f"* Tokenizer: `{result['tokenizer']}` (tiktoken {result['tiktoken']}).",
        f"* Machine: {m['os']}, {m['cpus']} CPUs, Python {m['python']}"
        + (f"; load average {load[0]:.2f} at the end of the run."
           " Compare sides within this run, not across machines." if load else "."),
        f"* Repetitions: {result['reps']} per task and side, run interleaved. Tokens and wall clock "
        "are medians."
        + (f" Each repetition waited for the 1-minute load average to drop below {max_load:.2f}."
           if gate else ""),
        *([f"* All {len(rep_loads)} repetitions started below the {max_load:.2f} load gate."]
          if quiet else
          ["* Timing columns are provisional: at least one repetition lacks a below-limit load record."]
          if gate else
          [f"* Timing columns are provisional until a quiet-machine re-run: this run recorded load "
            f"average {load_mark:.2f} on {m['cpus']} CPUs against a {max_load:.2f} gate."]
          if load_mark is not None and load_mark >= max_load else
          ["* Timing columns are provisional until a quiet-machine re-run: this run recorded no "
           "load average."] if load_mark is None else []),
        "* Subjects, fetched and built at the pinned commits in [`../servers.json`](../servers.json): "
        + ", ".join(f"{s['repo'].rsplit('/', 2)[-2]}/{s['repo'].rsplit('/', 1)[-1]} {s['ref']} "
                    f"({s['stars_at_selection']:,} stars)" for s in servers)
        + ". Installed and run on this machine with the commands in the method"
        + ("; both answered tool calls." if {s['id'] for s in servers} <= ran else "; not every server answered."),
        "* Local paths in the JSON are scrubbed after token counting; token counts describe the original calls.",
        "",
        "Reproduce (both servers built first, work directory outside the repository):",
        "",
        "```bash",
        "python bench/fetch_servers.py --workdir /tmp/kce-bench --kicad-python /usr/bin/python3",
        "python scripts/fetch_fixtures.py",
        f"TMPDIR=/tmp uv run --no-project --with tiktoken==0.14.0 python bench/run_bench.py --workdir /tmp/kce-bench "
        f"--reps {result['reps']}"
        + (f" --max-load {max_load} --max-wait {gate['max_wait_seconds']}" if gate else ""),
        "python bench/summarize.py bench/results/results-<date>.json",
        "```",
        "",
        *(["## Load gate records", "", "| Repetition (zero based) | 1-minute load | Wait (s) | Above limit |",
           "|---|---:|---:|---|",
           *(f"| {r['rep']} | {r['loadavg']} | {r['waited_seconds']} | {r['started_above_limit']} |"
             for r in rep_loads), ""] if rep_loads else []),
        "## 1. Context overhead — tokens before any work",
        "",
        "Counted as in the method: MCP tool definitions are `name`, `description` and `input_schema` "
        "as JSON; kce is the skill frontmatter (always in the system prompt) and the SKILL.md body "
        "(read once when the skill triggers).",
        "",
        "| Side | Tools | Always loaded | With full instructions | Listed but not in context |",
        "|---|---:|---:|---:|---|",
        *context_rows(ctx),
        "",
        "MCP server startup (reported separately, not part of any task): "
        + ", ".join(f"{k} {v['startup_seconds']} s" for k, v in ctx.items() if k != "kce") + ".",
        "",
        "## 2. Tasks — same job on a fresh copy of the demo",
        "",
        "Each side's own way (task → tool mapping in the method). `calls` is the number of tool "
        "calls or shell commands; token counts are the request (the call the agent emits) plus the "
        "response (the text it receives back).",
        "",
        "| Task | Side | Calls | Request + response tokens | Total | Median (s) | Min–max (s) |",
        "|---|---|---:|---:|---:|---:|---:|",
        *task_rows(result),
        "",
        f"{ok} of {total_runs} runs of a supported task returned success and {produced} of "
        f"{total_runs} produced the expected output (Gerber and drill files, BOM CSV on disk; "
        "ERC/DRC a violation count).",
        *(["", "Runs that did not count as produced:", "", *failed_runs(result)] if failed_runs(result) else []),
        "",
        "## Raw data",
        "",
        f"* [`{json_name}`]({json_name}) — everything above plus every run, each call's label, "
        "token split, seconds and the first 400 characters of its response.",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("results", help="results JSON written by run_bench.py")
    a = ap.parse_args()
    path = Path(a.results)
    result = json.loads(path.read_text(encoding="utf-8"))
    text = render(result, path.name)
    out = path.with_name(f"SUMMARY-{path.stem.split('-', 1)[1]}.md")
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
